"""state_layer —— 市场状态层（因果层的上游）。

职责
----
从**市场观测**（量价、波动、宽度、资金活动）识别"现在处于什么状态"，
输出可被其他层直接消费的状态序列。

与因果层的关系
--------------
`state_layer` 是**上游**：它只回答"现在像什么"，不回答"为什么"。
causual 拿它的输出当数据用（就像拿 csi_all 一样），不 import 它的内部。

为什么不和"资金诊断"分开
------------------------
市场状态与资金行为高度相关，而且两边都有大量定性成分
（状态靠聚类后命名，资金除了两融/ETF 这类直接观测外也是定性判断）。
硬拆成两套只会得到两个都说不清的系统。
但**资金观测是否进入状态估计**，由各资产的 features 决定——门开着，不预设结论。

目录
----
```
config/         每个资产的参数（K、特征清单、极端阈值）
features/       每个资产的特征构造（面板 → 特征矩阵）
estimators/     状态估计器（base 定义协议，hmm 是第一个实现）
postprocessors/ 后处理（极端行情规则覆盖）
inference.py    对外推理 + 输出契约
stats.py        状态画像
web/            页面
```
"""

